"""M-C: coupled discrepancy model over [FF, N2, N1, EGT] per engine (PREREGISTRATION section 3; amendment A3).

Form: VAR(p) with cross terms, one per engine position k (p <= 8, chosen by BIC on CAL, common to the four
positions), fitted by OLS on CAL residuals AFTER M-A and BEFORE M-B:
    r_k(t) = measured_k(t) - M-A_k(t)   (CAL-fitted unit offsets; running samples; first 60 s of segments dropped)
The residual is band-limited before fitting: r - lowpass(r, 0.01 Hz) (Butterworth-4 zero phase, the round-1
lowpass). M-C represents the coupled mid/fast-band discrepancy (0.01 Hz to Nyquist); slow (< 0.01 Hz) model
error is NOT regenerated (it remains M-A's error and shows in B5/B6). Channels are standardised by their CAL
residual SD for fitting.
Innovations: one 16x16 Gaussian covariance over the four engines' innovations (estimated on CAL samples where all
four engines run; amendment A3 ii), with the quantiser and M-B sensor-noise variance removed from the
diagonal (they are generated by M-B) and the result projected to the nearest PSD matrix (eigenvalue floor 0).
Generation: state reset to zero at the start of each running segment, 200-sample warm-up drawn before the segment,
output zero where the engine does not run. Stationarity: companion spectral radius must be < 0.999 (checked).
"""
import numpy as np
from numba import njit

import r2common as R

ORDER = ["FF", "N2", "N1", "EGT"]
HP_FC = 0.01
WARM = 200


@njit(cache=True)
def _var_sim(A, E, start, run, p, warm_e):
    """A: (4 engines, 4, 4p) coefficient blocks; E: (n, 16) innovations; warm_e: (warm, 16).
    Returns X (n, 16)."""
    n = E.shape[0]
    X = np.zeros((n, 16))
    H = np.zeros((4, p, 4))          # history per engine: H[k, j] = x(t-1-j)
    for t in range(n):
        for k in range(4):
            if not run[k, t]:
                for j in range(p):
                    for c in range(4):
                        H[k, j, c] = 0.0
                continue
            if start[k, t]:
                for j in range(p):
                    for c in range(4):
                        H[k, j, c] = 0.0
                for w in range(warm_e.shape[0]):
                    x = np.zeros(4)
                    for c in range(4):
                        acc = warm_e[w, 4 * k + c]
                        for j in range(p):
                            for c2 in range(4):
                                acc += A[k, c, 4 * j + c2] * H[k, j, c2]
                        x[c] = acc
                    for j in range(p - 1, 0, -1):
                        for c in range(4):
                            H[k, j, c] = H[k, j - 1, c]
                    for c in range(4):
                        H[k, 0, c] = x[c]
            x = np.zeros(4)
            for c in range(4):
                acc = E[t, 4 * k + c]
                for j in range(p):
                    for c2 in range(4):
                        acc += A[k, c, 4 * j + c2] * H[k, j, c2]
                x[c] = acc
            for j in range(p - 1, 0, -1):
                for c in range(4):
                    H[k, j, c] = H[k, j - 1, c]
            for c in range(4):
                H[k, 0, c] = x[c]
                X[t, 4 * k + c] = x[c]
    return X


def lagged(Z, p):
    """Z: (L, 4) -> X (L-p, 4p) with blocks [z(t-1), ..., z(t-p)], Y (L-p, 4)."""
    L = Z.shape[0]
    X = np.hstack([Z[p - j - 1:L - j - 1] for j in range(p)])
    return X, Z[p:]


class MC:
    def __init__(self, params=None):
        self.P = params

    # ---------------------------------------------------------------- fitting
    @staticmethod
    def residual_series(d, ma):
        """Band-limited M-A residuals per engine running segment: list of (k, a, b, Z (L, 4) physical units)."""
        import ma_model as MAM
        from pipeline import lowpass
        run = MAM.running_mask_cal(d)
        B = MAM.Batch([d], [run], with_outputs=False, min_len_s=120.0, burn_s=0.0)
        sim = ma.simulate(B)                 # CAL-fitted unit parameters
        out = []
        pos = 0
        burn = int(MAM.BURN_S * R.RATE)
        for (fi, k, a, b) in B.seg:
            L = b - a
            Z = np.column_stack([d["Y"][c][k, a:b] - sim[c][pos:pos + L] for c in ORDER])
            pos += L
            Z = Z - np.column_stack([lowpass(Z[:, j], R.RATE, HP_FC) for j in range(4)])
            out.append((k, a + burn, b, Z[burn:]))
        return out

    @classmethod
    def fit(cls, flights, ma, mbp, pmax=8, log=print):
        series = [cls.residual_series(d, ma) for d in flights]
        # scales: SD per (engine, channel)
        ss = np.zeros((4, 4))
        nn = np.zeros(4)
        for fl in series:
            for k, a, b, Z in fl:
                ss[k] += (Z ** 2).sum(0)
                nn[k] += Z.shape[0]
        scale = np.sqrt(ss / nn[:, None])
        # sufficient statistics for p = pmax (same samples for every p <= pmax)
        XtX = np.zeros((4, 4 * pmax, 4 * pmax))
        XtY = np.zeros((4, 4 * pmax, 4))
        YtY = np.zeros((4, 4, 4))
        cnt = np.zeros(4)
        for fl in series:
            for k, a, b, Z in fl:
                if Z.shape[0] <= pmax + 10:
                    continue
                X, Y = lagged(Z / scale[k], pmax)
                XtX[k] += X.T @ X
                XtY[k] += X.T @ Y
                YtY[k] += Y.T @ Y
                cnt[k] += Y.shape[0]
        bic = {}
        coefs = {}
        for p in range(1, pmax + 1):
            m = 4 * p
            tot = 0.0
            cf = []
            for k in range(4):
                A = np.linalg.solve(XtX[k][:m, :m], XtY[k][:m])          # (4p, 4)
                S = (YtY[k] - A.T @ XtY[k][:m]) / cnt[k]
                tot += cnt[k] * np.log(np.linalg.det(S)) + np.log(cnt[k]) * (16 * p)
                cf.append(A.T)                                           # (4, 4p)
            bic[p] = float(tot)
            coefs[p] = cf
        p = min(bic, key=bic.get)
        A = np.array(coefs[p])
        # stationarity
        rad = []
        for k in range(4):
            comp = np.zeros((4 * p, 4 * p))
            comp[:4] = A[k]
            comp[4:, :-4] = np.eye(4 * (p - 1))
            rad.append(float(np.max(np.abs(np.linalg.eigvals(comp)))))
        log(f"  M-C VAR order by BIC: p={p}; companion spectral radius per engine {np.round(rad, 4).tolist()}")
        # innovations (standardised units) at times where all four engines run
        Sig = np.zeros((16, 16))
        ns = 0
        for d, fl in zip(flights, series):
            n = d["n"]
            E = np.full((n, 16), np.nan)
            for k, a, b, Z in fl:
                if Z.shape[0] <= p + 10:
                    continue
                X, Y = lagged(Z / scale[k], p)
                e = Y - X @ A[k].T
                E[a + p:b, 4 * k:4 * k + 4] = e
            ok = np.all(np.isfinite(E), 1)
            Eo = E[ok]
            Sig += Eo.T @ Eo
            ns += Eo.shape[0]
        Sig /= max(ns, 1)
        # remove quantiser + M-B noise variance from the diagonal (they are generated by M-B)
        rem = np.zeros(16)
        import mb_model as MBM
        for k in range(4):
            for c, ch in enumerate(ORDER):
                L = R.LSB_REC[ch]
                q2 = L ** 2 / 12 + ((MBM.NATIVE[ch] * L) ** 2 / 12 if MBM.NATIVE[ch] else 0.0)
                s2 = mbp["noise"][f"{ch}_{k + 1}"]["sigma"] ** 2
                rem[4 * k + c] = (q2 + s2) / scale[k, c] ** 2
        Sc = Sig - np.diag(np.minimum(rem, 0.9 * np.diag(Sig)))
        w, V = np.linalg.eigh(Sc)
        Sc = (V * np.maximum(w, 0)) @ V.T
        corr = Sig / np.sqrt(np.outer(np.diag(Sig), np.diag(Sig)))
        params = {"order": ORDER, "p": int(p), "bic": bic, "A": A.tolist(), "scale": scale.tolist(),
                  "Sigma_std": Sc.tolist(), "Sigma_std_raw": Sig.tolist(), "innov_corr_raw": corr.tolist(),
                  "removed_diag_var_std": rem.tolist(), "spectral_radius": rad, "hp_fc_hz": HP_FC,
                  "n_innov_samples": int(ns), "n_samples_per_engine": cnt.tolist()}
        return cls(params)

    # ---------------------------------------------------------------- generation
    def simulate(self, run, fid):
        """run: (4, n) bool engine running mask. Returns {fam: (4, n)} physical-unit discrepancy."""
        P = self.P
        p = P["p"]
        A = np.array(P["A"])
        scale = np.array(P["scale"])
        S = np.array(P["Sigma_std"])
        w, V = np.linalg.eigh(S)
        Lc = V * np.sqrt(np.maximum(w, 0))
        n = run.shape[1]
        rng = R.rng_for(fid, "MC_innov")
        E = rng.standard_normal((n, 16)) @ Lc.T
        W = rng.standard_normal((WARM, 16)) @ Lc.T
        start = np.zeros_like(run)
        start[:, 0] = run[:, 0]
        start[:, 1:] = run[:, 1:] & ~run[:, :-1]
        X = _var_sim(A, E, start, run, p, W)
        out = {}
        for c, ch in enumerate(ORDER):
            out[ch] = np.vstack([X[:, 4 * k + c] * scale[k, c] for k in range(4)])
        return out
