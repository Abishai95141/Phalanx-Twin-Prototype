def expand(o):
    """Inverse of final._round's compact records: {m, l, h, n} -> median/lo/hi/n, {v, l, h} -> value/lo/hi."""
    if isinstance(o, dict):
        if set(o) == {"m", "l", "h", "n"}:
            return {"median": o["m"], "lo": o["l"], "hi": o["h"], "n": o["n"]}
        if set(o) == {"v", "l", "h"}:
            return {"value": o["v"], "lo": o["l"], "hi": o["h"]}
        return {k: expand(v) for k, v in o.items()}
    if isinstance(o, list):
        return [expand(v) for v in o]
    return o


def _ok(*v) -> bool:
    return all(x is not None and x == x for x in v)


def f(m: dict | None, nd: int = 2) -> str:
    if not m or m.get("n", 1) == 0 or not _ok(m.get("median"), m.get("lo"), m.get("hi")):
        return "n/a"
    return f"{m['median']:.{nd}f} [{m['lo']:.{nd}f}, {m['hi']:.{nd}f}]"


def fp(m: dict | None, nd: int = 2) -> str:
    if not m or not _ok(m.get("value"), m.get("lo"), m.get("hi")):
        return "n/a"
    return f"{m['value']:.{nd}f} [{m['lo']:.{nd}f}, {m['hi']:.{nd}f}]"


