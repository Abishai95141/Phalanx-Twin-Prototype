"""W2.4a-2 stage 1: steady relations of the proxy plant against CAL (tables from ``st_ident.py`` outputs).

For each assessed point set (bins of real quasi-steady points with the model at the same condition), per
regime and per corrected-core-speed band: the real and model corrected relations g (FF/(delta sqrt(theta)) vs
N2/sqrt(theta)), h (N1/sqrt(theta) vs N2/sqrt(theta)) and the EGT, as point-weighted medians, plus the
altitude trend of the residuals (the signature of altitude effects the plant lacks).

Usage::

    $PY -I analysis/proxy_quicklook/code/st_report.py <out.md> <label=assess.json> ...
"""

from __future__ import annotations

import json
import math
import sys

import numpy as np

BANDS = ((40, 55), (55, 65), (65, 75), (75, 85), (85, 90), (90, 93), (93, 96), (96, 101))
ALT_BANDS = ((-2000, 5000), (5000, 15000), (15000, 25000), (25000, 45000))


def isa_delta(alt_ft: float) -> float:
    h = float(alt_ft)
    return (1.0 - 6.87559e-6 * min(h, 36089.0)) ** 5.2559 * math.exp(-4.80634e-5 * max(h - 36089.0, 0.0))


def _corr(b: dict) -> dict:
    th = (b["TAT"] + 273.15) / 288.15
    de = isa_delta(b["ALT"]) * (1 + 0.2 * b["MACH"] ** 2) ** 3.5
    return {"th": th, "n2c": b["N2"] / math.sqrt(th), "wfc": b["FF"] / (de * math.sqrt(th)),
            "wfc_m": b["model_ff"] / (de * math.sqrt(th)), "n1c": b["N1"] / math.sqrt(th),
            "n1c_m": b["model_n1"] / math.sqrt(th)}  # fmt: skip


def wmed(x, w) -> float:
    x = np.asarray(x, float)
    w = np.asarray(w, float)
    if x.size == 0:
        return math.nan
    o = np.argsort(x)
    c = np.cumsum(w[o])
    return float(x[o][np.searchsorted(c, 0.5 * c[-1])])


def tables(label: str, d: dict) -> list[str]:
    bins = [b for b in d["bins"] if b["ok"]]
    out = [
        f"\n### {label}: {d['n_points']} points in {d['n_bins']} bins ({d.get('failed', 0)} failed solves)\n"
    ]
    out.append(
        "| N2c band [%] | where | points | Wfc real / model [lb/h] | N1c real / model [%] | EGT real / model "
        "[degC] |"
    )
    out.append("|---|---|---|---|---|---|")
    for lo, hi in BANDS:
        for where, sel in (("ground", lambda b: b["ground"]), ("flight", lambda b: not b["ground"])):
            bb = [b for b in bins if sel(b) and lo <= _corr(b)["n2c"] < hi]
            if not bb:
                continue
            w = [b["n"] for b in bb]
            c = [_corr(b) for b in bb]
            out.append(
                f"| {lo}-{hi} | {where} | {sum(w)} | {wmed([x['wfc'] for x in c], w):.0f} / "
                f"{wmed([x['wfc_m'] for x in c], w):.0f} | {wmed([x['n1c'] for x in c], w):.1f} / "
                f"{wmed([x['n1c_m'] for x in c], w):.1f} | {wmed([b['EGT'] for b in bb], w):.0f} / "
                f"{wmed([b['model_egt'] for b in bb], w):.0f} |"
            )
    out.append("\nResiduals (model - real; FF as a ratio - 1) by altitude, flight bins at N2c >= 85 %:\n")
    out.append("| altitude [ft] | points | FF | N1 [%] | EGT [K] |")
    out.append("|---|---|---|---|---|")
    for lo, hi in ALT_BANDS:
        bb = [b for b in bins if not b["ground"] and lo <= b["ALT"] < hi and _corr(b)["n2c"] >= 85]
        if not bb:
            continue
        w = [b["n"] for b in bb]
        out.append(
            f"| {lo}-{hi} | {sum(w)} | {wmed([b['model_ff'] / b['FF'] - 1 for b in bb], w):+.3f} | "
            f"{wmed([b['model_n1'] - b['N1'] for b in bb], w):+.2f} | "
            f"{wmed([b['model_egt'] - b['EGT'] for b in bb], w):+.1f} |"
        )
    return out


def main(out_md: str, *specs: str) -> None:
    lines = ["# Stage-1 steady relations against CAL (generated by code/st_report.py)"]
    for sp in specs:
        label, path = sp.split("=", 1)
        lines += tables(label, json.load(open(path)))
    with open(out_md, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], *sys.argv[2:])
