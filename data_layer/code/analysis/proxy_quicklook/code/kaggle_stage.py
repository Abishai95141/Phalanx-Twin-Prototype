"""Stage a private Kaggle dataset + kernel for a W2.4a-2 run that exceeds the local compute rule (> ~1
CPU-hour, coordinator process rule; RULES.md section 8). Nothing here talks to Kaggle: it builds two
folders and writes the exact commands to ``analysis/proxy_quicklook/kaggle_pending_cmds.txt`` for the
coordinating session.

Dataset folder (``<out>/ds``): a code snapshot (``src``, ``configs``, ``tools``, ``pyproject.toml``,
``uv.lock``, ``docs/assumptions.md`` (the parameter loader checks assumption ids), the analysis code it runs
and the small result files it reads), the run spec, and **only** the MAT files of the run's flight lists,
copied through the path guards (``proxy.guard.check_path`` refuses archive 2; the quick-look guard admits
only the listed 652 / 687-TEST files). Kernel folder (``<out>/kernel``): ``run.py`` and
``kernel-metadata.json`` (private, CPU, internet on for the pinned environment). The kernel builds the
pinned environment from ``uv.lock`` with ``uv`` (Python 3.13, ``uv sync --frozen --no-dev``), records it in
``env.json``, runs the script with ``python -I``, and exits non-zero when any step fails.

Usage::

    $PY -I analysis/proxy_quicklook/code/kaggle_stage.py quicklook <mat687> <mat652> <spec.json> <out> <slug>
"""

from __future__ import annotations

import json
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I drops the script directory

from common import REPO

USER = "abishaicenthil"
CODE_FILES = (
    "analysis/proxy_quicklook/code",
    "analysis/mf1_lp_structure/code",
)
DATA_FILES = (
    "analysis/settling_experiment/results/splits.csv",
    "analysis/mf1_lp_structure/results/flight_order.json",
    "analysis/settling_experiment_round2/results/holdout_652_s20/list_holdout.txt",
    "analysis/settling_experiment_round2/results/holdout_652_s20/list_partner.txt",
    "analysis/settling_experiment_round2/results/holdout_652_s20/list_early.txt",
    "analysis/settling_experiment_round2/results/holdout_652_s20/list_late.txt",
    "analysis/settling_experiment_round2/results/holdout_652_s20/battery.json",
    "docs/assumptions.md",
    "pyproject.toml",
    "uv.lock",
)
TREES = ("src", "configs", "tools")

RUN_PY = r'''"""Kaggle kernel: W2.4a-2 {what} (private). Builds the pinned environment from uv.lock,
runs, exits non-zero on any failure. Generated by analysis/proxy_quicklook/code/kaggle_stage.py."""
import json, os, platform, shutil, subprocess, sys, time

OUT = "/kaggle/working"
env = {{"started": time.strftime("%Y-%m-%dT%H:%M:%S"), "kernel_python": sys.version, "cpu": os.cpu_count(),
       "platform": platform.platform()}}


def save():
    with open(os.path.join(OUT, "env.json"), "w") as fh:
        json.dump(env, fh, indent=1)


save()
root = None
for d, dirs, files in os.walk("/kaggle/input"):
    if "PHALANX_DATASET" in files:
        root = d
        break
if root is None:
    env["error"] = "dataset root (PHALANX_DATASET marker) not found"; save(); sys.exit(2)
repo = "/tmp/repo"  # outside /kaggle/working: only out/ and env.json are kernel outputs
shutil.copytree(os.path.join(root, "repo"), repo)
env["dataset_root"] = root


def run(cmd, **kw):
    print("+", " ".join(cmd), flush=True)
    r = subprocess.run(cmd, **kw)
    if r.returncode != 0:
        env["error"] = f"failed ({{r.returncode}}): {{' '.join(cmd)}}"; save(); sys.exit(r.returncode)


run([sys.executable, "-m", "pip", "install", "-q", "uv==0.11.23"])
run(["uv", "python", "install", "3.13.3"])
run(["uv", "sync", "--frozen", "--no-dev", "--python", "3.13.3"], cwd=repo)
py = os.path.join(repo, ".venv", "bin", "python")
frz = subprocess.run([py, "-I", "-m", "pip", "freeze"], capture_output=True, text=True)
if frz.returncode != 0:
    frz = subprocess.run(["uv", "pip", "freeze", "--python", py], capture_output=True, text=True, cwd=repo)
env["venv_python"] = subprocess.run([py, "-I", "--version"], capture_output=True, text=True).stdout.strip()
env["freeze"] = frz.stdout.splitlines()
save()
t0 = time.time()
run([py, "-I", os.path.join(repo, "{script}"), {args}], cwd=repo)
env["run_seconds"] = round(time.time() - t0, 1)
env["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S")
save()
'''


def _copy_tree(src: str, dst: str) -> None:
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"))


def stage_quicklook(mat687: str, mat652: str, spec_json: str, out: str, slug: str) -> None:
    from st6_quicklook import lists, path_of

    ds = os.path.join(out, "ds")
    kn = os.path.join(out, "kernel")
    if os.path.exists(out):
        raise FileExistsError(f"{out} exists; stage into a fresh folder")
    repo = os.path.join(ds, "repo")
    os.makedirs(repo)
    for t in TREES:
        _copy_tree(str(REPO / t), os.path.join(repo, t))
    for c in CODE_FILES:
        _copy_tree(str(REPO / c), os.path.join(repo, c))
    for f in DATA_FILES:
        os.makedirs(os.path.dirname(os.path.join(repo, f)), exist_ok=True)
        shutil.copy2(REPO / f, os.path.join(repo, f))
    shutil.copy2(spec_json, os.path.join(repo, "spec.json"))
    L = lists()
    files = L["holdout"] + L["partner"]
    for sub in ("mat687", "mat652"):
        os.makedirs(os.path.join(repo, sub))
    for f in files:
        p = path_of(f, mat687, mat652)  # guards: listed 652 / 687-TEST files only; archive 2 refused
        sub = "mat652" if f.startswith("652") else "mat687"
        shutil.copy2(p, os.path.join(repo, sub, f))
    open(os.path.join(ds, "PHALANX_DATASET"), "w").write("w2.4a-2 quick look\n")
    with open(os.path.join(ds, "dataset-metadata.json"), "w") as fh:
        json.dump({"title": slug, "id": f"{USER}/{slug}", "licenses": [{"name": "other"}]}, fh, indent=1)
    os.makedirs(kn)
    args = ", ".join(repr(a) for a in ("mat687", "mat652", "spec.json", "/kaggle/working/out", "4"))
    with open(os.path.join(kn, "run.py"), "w") as fh:
        fh.write(
            RUN_PY.format(
                what="quick look (stage 6)",
                script="analysis/proxy_quicklook/code/st6_quicklook.py",
                args=args,
            )
        )
    meta = {
        "id": f"{USER}/{slug}-run",
        "title": f"{slug}-run",
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [f"{USER}/{slug}"],
        "competition_sources": [],
        "kernel_sources": [],
    }
    with open(os.path.join(kn, "kernel-metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=1)
    n_mat = len(files)
    print(f"staged {out}: {n_mat} MAT files ({sum(1 for f in files if f.startswith('652'))} Tail 652)")


def main(kind: str, *args: str) -> None:
    if kind != "quicklook":
        raise SystemExit(f"unknown kind {kind!r}")
    stage_quicklook(*args)


if __name__ == "__main__":
    main(*sys.argv[1:])
