def verify(sortie_id: str, out: Path) -> dict[str, Any]:
    """Regenerate one telemetry sortie in a fresh process into a scratch tree and compare the bytes of every
    file of its partitions with the published tree."""
    commit = git_commit()
    with tempfile.TemporaryDirectory(prefix="preview-verify-", dir=_ensure(out / "_work")) as tmp:
        tmp_out = Path(tmp)
        subprocess.run(
            [
                sys.executable,
                "-I",
                str(Path(__file__).resolve()),
                "telemetry",
                "--sortie",
                sortie_id,
                "--out",
                str(tmp_out),
            ],
            check=True,
        )
        tail = sortie_id.split("-")[0]
        mismatches, compared = [], 0
        for tree in ("telemetry", "_restricted_labels/telemetry"):
            a = sorted(
                p.relative_to(out / tree)
                for p in (out / tree).rglob("*.parquet")
                if f"sortie_id={sortie_id}" in str(p)
                or (f"tail_no={tail}" in str(p) and "sortie_id=__null__" in str(p))
            )
            b = (
                sorted(p.relative_to(tmp_out / tree) for p in (tmp_out / tree).rglob("*.parquet"))
                if (tmp_out / tree).exists()
                else []
            )
            if a != b:
                mismatches.append(f"{tree}: file sets differ ({len(a)} vs {len(b)})")
                continue
            for rel in a:
                compared += 1
                if (out / tree / rel).read_bytes() != (tmp_out / tree / rel).read_bytes():
                    mismatches.append(f"{tree}/{rel}: bytes differ")
    doc = {
        "sortie_id": sortie_id,
        "files_compared": compared,
        "identical": not mismatches and compared > 0,
        "mismatches": mismatches,
        "code_commit": commit,
    }
    _write_json(out / "_runs" / "determinism" / f"{sortie_id}.json", doc)
    return doc


