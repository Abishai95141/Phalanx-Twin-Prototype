# ============================================================================================== helpers
def git_commit() -> str:
    return subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.strip()


def _contract():
    from phalanx.dictionary.contract import load_contract

    return load_contract("v0")


def _stores(out: Path, tree: str):
    from phalanx.streaming.parquet_store import ParquetStore

    return ParquetStore(out / tree, _contract(), restricted_root=out / "_restricted_labels" / tree)


def _write_json(path: Path, doc: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")


def _recordable(ss) -> list[str]:
    """Every channel the integrated aircraft can record: M12 sensor channels + LRU-computed values (AD-42)."""
    from phalanx.integration.sortie import _recorded_sources

    return sorted(set(ss.sensor_config.channels) | set(_recorded_sources(ss)))


def _plan(sortie_id: str):
    from phalanx.integration.plans import gate_sorties

    for p in gate_sorties(days=PLAN_DAYS):
        if p.sortie_id == sortie_id:
            return p
    raise KeyError(f"{sortie_id} is not in the {PLAN_DAYS}-day gate plan")


def _download_ingest(ident, t_end: int) -> tuple[int, list[dict[str, Any]]]:
    """M16's download model for a recording that stopped at ``t_end``: the arrival of the first complete
    delivery (the instant the whole sortie's data exist on the ground) and every delivery's timing."""
    from phalanx.bus.clocks import STREAMS as BUS_STREAMS
    from phalanx.core.rng import RngService, StreamRegistry
    from phalanx.recorder.download import DownloadConfig, simulate_download
    from phalanx.recorder.writer import STREAMS as REC_STREAMS

    rng = RngService(TELEMETRY_ROOT, StreamRegistry([*BUS_STREAMS, *REC_STREAMS]))
    dls = simulate_download(b"\0", int(t_end), ident, rng, DownloadConfig.from_params())
    first = next(d for d in dls if d.complete)
    return int(first.t_ingest), [
        {"attempt": d.attempt, "t_ingest": int(d.t_ingest), "complete": bool(d.complete)} for d in dls
    ]


def _ident(ss):
    from phalanx.bus.clocks import SortieIdentity

    w = ss.window
    return SortieIdentity(
        scenario=TELEMETRY_SCENARIO,
        tail_no=w.tail,
        sortie_id=w.sortie_id,
        engine_serial=w.engine_serials[0] if w.engine_serials else None,
    )


def _abort_doc(e) -> dict[str, Any] | None:
    if e is None:
        return None
    return {"kind": e.kind, "message": str(e), "t_s": e.k / 240.0, "phase": e.phase}


# ============================================================================================== telemetry
def run_telemetry(
    sortie_id: str, out: Path, *, commit: str | None = None, max_s: int | None = None
) -> dict[str, Any]:
    """One telemetry sortie, fast path, to ``out/telemetry`` (module docstring). ``max_s``: smoke runs only
    (stop after that many flown seconds; the outcome says ``truncated``)."""
    from phalanx.core.numba_cache import configure_numba_cache

    configure_numba_cache()
    import pyarrow as pa
    import pyarrow.parquet as pq

    from phalanx.ground.cir import CirBatch
    from phalanx.ground.fast_path import FastPathConfig, cir_to_param_samples
    from phalanx.integration.sortie import SortieAborted, SortieRunner
    from phalanx.integration.system import SortieSpec, build_sortie_system
    from phalanx.monitoring.contract_out import contract_tables
    from phalanx.scenario.config import MISSION_NAMES
    from phalanx.streaming.parquet_store import utc_date

    t_wall = time.time()
    commit = commit or git_commit()
    plan = _plan(sortie_id)
    ss = build_sortie_system(SortieSpec(plan=plan, scenario=TELEMETRY_SCENARIO, root=TELEMETRY_ROOT))
    d, w = ss.dictionary, ss.window
    r = SortieRunner(ss, cir_channels=_recordable(ss), keep_cir=True, git_commit=commit)
    cfg = FastPathConfig.from_dictionary(d, engine_serial=w.engine_serials[0])
    work = Path(tempfile.mkdtemp(prefix=f"stage-{sortie_id}-", dir=_ensure(out / "_work")))
    st = r.begin()
    abort = None
    buf: list[pa.Table] = []
    buf_steps = 0
    segs: list[Path] = []
    n_cir = 0

    def flush() -> None:
        nonlocal buf, buf_steps, n_cir
        if not buf:
            return
        cir = pa.concat_tables(buf)
        n_cir += cir.num_rows
        ps = cir_to_param_samples(CirBatch(w.tail, w.sortie_id, cir), cfg, t_ingest=_PROVISIONAL_INGEST)
        p = work / f"seg-{len(segs):04d}.parquet"
        pq.write_table(ps, p)
        segs.append(p)
        buf, buf_steps = [], 0

    k_max = None if max_s is None else int(max_s) * 240
    while st.world.k < r.end_step(st) and (k_max is None or st.world.k < k_max):
        try:
            st, outs = r.run(st, min(r.chunk, r.end_step(st) - st.world.k))
        except SortieAborted as e:
            abort = e
            break
        for c in outs:
            buf.append(c.cir.table if hasattr(c.cir, "table") else c.cir)
            buf_steps += c.trace.ports["af.nz"].shape[0]
        if buf_steps >= SEGMENT_S * 240:
            flush()
    flush()
    truncated = abort is None and st.world.k < r.end_step(st)
    if abort is None and not truncated:
        st = r.close(st)
    t_start = ss.epoch_utc_ns
    t_end = ss.epoch_utc_ns + st.world.k * NS // 240
    t_ing, deliveries = _download_ingest(_ident(ss), t_end)
    date = utc_date(t_start)
    store = _stores(out, "telemetry")
    counts: dict[str, int] = {}
    for p in segs:
        ps = pq.read_table(p)
        ps = ps.set_column(
            ps.schema.get_field_index("t_ingest"),
            ps.schema.field("t_ingest"),
            pa.array([t_ing] * ps.num_rows, pa.int64()),
        )
        store.write("param.samples", ps, date=date)
        counts["param.samples"] = counts.get("param.samples", 0) + ps.num_rows
    shutil.rmtree(work)
    mon = ss.modules["monitor"]
    tabs = contract_tables(
        mon,
        st.world.states["monitor"],
        dictionary=d,
        tail_no=w.tail,
        epoch_utc_ns=ss.epoch_utc_ns,
        t_ingest_utc_ns=t_ing,
    )
    for topic, tab in sorted(tabs.items()):
        store.write(topic, tab, date=date)
        counts[topic] = tab.num_rows
    man = r.manifest(st, t_ingest=t_ing)
    store.write("sortie.manifest", man, date=date)
    counts["sortie.manifest"] = man.num_rows
    doc = {
        "preview": PREVIEW_LABEL,
        "kind": "telemetry",
        "sortie_id": w.sortie_id,
        "tail_no": w.tail,
        "mission_type": MISSION_NAMES.get(int(w.mission_type), str(w.mission_type)),
        "completed": abort is None and not truncated,
        "truncated": truncated,
        "abort": _abort_doc(abort),
        "flown_s": st.world.k / 240.0,
        "planned_window_s": int(ss.window.t_end_off_ns) / NS,
        "t_takeoff": man.column("t_takeoff")[0].as_py(),
        "t_landing": man.column("t_landing")[0].as_py(),
        "t_start": t_start,
        "t_end": t_end,
        "t_ingest": t_ing,
        "deliveries": deliveries,
        "cir_rows": n_cir,
        "recorded_channels": len(r.cir_channels),
        "rows": counts,
        "root_seed_hex": ss.system.rng.root_hex,
        "scenario": TELEMETRY_SCENARIO,
        "code_commit": commit,
        "wall_s": round(time.time() - t_wall, 1),
    }
    _write_json(out / "_runs" / "telemetry" / f"{w.sortie_id}.json", doc)
    return doc


def _ensure(p: Path) -> Path:
    p.mkdir(parents=True, exist_ok=True)
    return p


# ============================================================================================== full path
def run_full_path_window(
    out: Path,
    *,
    sortie_id: str = FULL_PATH_SORTIE,
    window_s: int = FULL_PATH_WINDOW_S,
    commit: str | None = None,
) -> dict[str, Any]:
    """The first ``window_s`` of one sortie through M15 -> M16 -> download -> M17 (provenance full_path)."""
    from phalanx.core.numba_cache import configure_numba_cache

    configure_numba_cache()
    import pyarrow as pa

    from phalanx.bus.clocks import STREAMS as BUS_STREAMS
    from phalanx.bus.clocks import acquisition_oscillators
    from phalanx.core.rng import RngService, StreamRegistry
    from phalanx.ground.cir import CirBatch
    from phalanx.integration.sortie import SortieAborted, SortieRunner
    from phalanx.integration.system import SortieSpec, build_sortie_system
    from phalanx.recorder.full_path import full_path_truth_labels, run_full_path
    from phalanx.recorder.writer import STREAMS as REC_STREAMS
    from phalanx.streaming.dedup import dedup_by_record_id
    from phalanx.streaming.parquet_store import utc_date

    t_wall = time.time()
    commit = commit or git_commit()
    c = _contract()
    plan = _plan(sortie_id)
    ss = build_sortie_system(SortieSpec(plan=plan, scenario=TELEMETRY_SCENARIO, root=TELEMETRY_ROOT))
    d, w = ss.dictionary, ss.window
    r = SortieRunner(ss, cir_channels=_recordable(ss), keep_cir=True, git_commit=commit)
    st = r.begin()
    abort = None
    parts = []
    k_target = min(window_s * 240, r.end_step(st))
    while st.world.k < k_target:
        try:
            st, outs = r.run(st, min(r.chunk, k_target - st.world.k))
        except SortieAborted as e:
            abort = e
            break
        parts += [o.cir.table if hasattr(o.cir, "table") else o.cir for o in outs]
    cir = CirBatch(w.tail, w.sortie_id, pa.concat_tables(parts))
    del parts
    t_start = ss.epoch_utc_ns
    t_end = ss.epoch_utc_ns + st.world.k * NS // 240
    rng = RngService(TELEMETRY_ROOT, StreamRegistry([*BUS_STREAMS, *REC_STREAMS]))
    res = run_full_path(
        cir,
        ident=_ident(ss),
        rng=rng,
        t_start=t_start,
        t_end=t_end,
        dictionary=d,
        contract=c,
        oscillators=acquisition_oscillators(d, ss.epoch_utc_ns),
    )
    samples, n_dup = dedup_by_record_id(c, "param.samples", res.samples())
    first = next(dl for dl in res.deliveries if dl.complete)
    date = utc_date(t_start)
    store = _stores(out, "telemetry_full_path")
    store.write("param.samples", samples, date=date)
    man = r.manifest(st, t_ingest=int(first.t_ingest), provenance="full_path")
    store.write("sortie.manifest", man, date=date)
    labels = full_path_truth_labels(res.recording, cir, contract=c, dictionary=d)
    store.write("labels.truth", labels, date=date)
    ch10 = _ensure(out / "ch10") / f"{w.sortie_id}.ch10"
    ch10.write_bytes(res.recording.data)
    doc = {
        "preview": PREVIEW_LABEL,
        "kind": "full_path",
        "sortie_id": w.sortie_id,
        "tail_no": w.tail,
        "window_s": st.world.k / 240.0,
        "completed_window": abort is None,
        "abort": _abort_doc(abort),
        "t_start": t_start,
        "t_end": t_end,
        "deliveries": [
            {
                "attempt": dl.attempt,
                "t_ingest": int(dl.t_ingest),
                "complete": bool(dl.complete),
                "bytes": len(dl.data),
            }
            for dl in res.deliveries
        ],
        "duplicates_dropped": int(n_dup) if isinstance(n_dup, int) else None,
        "ch10_file": str(ch10.relative_to(out)),
        "ch10_bytes": len(res.recording.data),
        "cir_rows": cir.table.num_rows,
        "rows": {
            "param.samples": samples.num_rows,
            "sortie.manifest": man.num_rows,
            "labels.truth": labels.num_rows,
        },
        "code_commit": commit,
        "wall_s": round(time.time() - t_wall, 1),
    }
    _write_json(out / "_runs" / "full_path" / f"{w.sortie_id}.json", doc)
    return doc


# ============================================================================================== fleet
def _fleet_world(k: int, days: int):
    """WorldBuilder of one tail: real M02 (operations mode), M18, M21 + record sink, and the real M10 / M11 /
    M14 of that tail (the W2.5 B8 pattern, ``analysis/faults_b7b8/code/fleet.py``: M18 addresses one
    health/monitoring module id per fleet, so one tail per world until W2.6's router)."""
    from phalanx.core.events import Event
    from phalanx.dictionary import load_dictionary
    from phalanx.environment.config import load_env_config
    from phalanx.faults import FaultConfig, FaultInjector, load_catalogue, load_fault_params, load_graph
    from phalanx.fork.builder import OpsIds, OpsOnlyBuilder
    from phalanx.health import HealthConfig, HealthModule, load_health_params, sensor_bias_channels
    from phalanx.maintenance.world import FleetSpec, OpsTargets
    from phalanx.monitoring import MonitoringConfig, MonitoringModule, load_code_table, load_monitoring_params
    from phalanx.scenario.config import FleetScenario, load_fleet_scenario, load_scenario_params
    from phalanx.scenario.module import EV_DAY, OpsLink, ScenarioModule

    ids = OpsIds()
    full = load_fleet_scenario(ROOT / "configs" / "scenarios" / "tejas_two_squadrons.yaml")
    sqs = full.squadrons
    tails = [t for sq in sqs for t in sq.tails]
    sers = [s for sq in sqs for s in sq.engine_serials]
    owner = next(sq for sq in sqs if tails[k] in sq.tails)
    tail, serial = tails[k], sers[k]
    one = type(owner)(owner.sid, owner.role, owner.base, (tail,), (serial,))
    fleet = FleetScenario(f"{FLEET_SCENARIO}-{tail}", FLEET_START, days, (one,))
    epoch = fleet.epoch_utc_ns
    d = load_dictionary()
    targets = OpsTargets(m21=ids.m21, sink=ids.sink, scenario="m02", health="m10", monitoring="m14")
    link = OpsLink(m18=ids.m18, health="m10", kpi=ids.sink)
    params, env = load_scenario_params(), load_env_config()
    bias = sensor_bias_channels(d)
    codes = load_code_table(d, load_monitoring_params())

    def m02():
        return ScenarioModule("m02", params, env, fleet=fleet, ops=link)

    def m10():
        cfg = HealthConfig((serial,), bias, "m11", monitor_target="m14", tail_no=tail)
        return HealthModule("m10", load_health_params(), config=cfg, identity={"tail": tail})

    def m11():
        cfg = FaultConfig(
            load_catalogue(),
            load_graph(),
            {"health": "m10", "monitoring": "m14", "maintenance": ids.m18, "ops": "m02"},
            (serial,),
            bias,
            realise_physics_edges=True,
            stochastic=True,
            tail_no=tail,
        )
        return FaultInjector("m11", load_fault_params(), config=cfg, identity={"tail": tail})

    def m14():
        cfg = MonitoringConfig.from_dictionary(
            d, codes, (serial,), regime=FLEET_REGIME, tail_no=tail, epoch_utc_ns=epoch, obs_target=ids.m18
        )
        return MonitoringModule("m14", load_monitoring_params(), config=cfg, identity={"tail": tail})

    class World:
        def __init__(self) -> None:
            self.ids = ids
            self.tail = tail
            self.epoch_utc_ns = epoch
            self.fleet_scenario = fleet
            self._ops = OpsOnlyBuilder(
                FleetSpec.from_scenario(fleet),
                epoch,
                scenario=FLEET_SCENARIO,
                targets=targets,
                ids=ids,
                extra=(m02, m10, m11, m14),
            )
            self.fleet = self._ops.fleet if hasattr(self._ops, "fleet") else None
            self.calendar = self._ops.calendar
            self.dict_version, self.dict_hash = self._ops.dict_version, self._ops.dict_hash
            self.dictionary = d

        def build(self, root, *, ledger=None):
            return self._ops.build(root, ledger=ledger)

        def initial_events(self):
            return [*self._ops.initial_events(), Event(0, EV_DAY, "m02", {"day": 0}, source="session")]

    return World()


def run_fleet(k: int, out: Path, *, days: int = FLEET_DAYS) -> dict[str, Any]:
    """One tail's usage-mode operations world for ``days`` with the scheduled reference policy (M21), to
    ``out/fleet`` (module docstring)."""
    import pyarrow as pa

    from phalanx.fork.kpi import compute_kpis
    from phalanx.fork.session import OpsSession
    from phalanx.health.protocol import read_payload
    from phalanx.maintenance import load_m18_config
    from phalanx.maintenance.defects import DefectInjector
    from phalanx.maintenance.records import rows_to_table
    from phalanx.monitoring.contract_out import contract_tables
    from phalanx.orders.policies import PolicyContext, ScheduledPolicy

    t_wall = time.time()
    c = _contract()
    b = _fleet_world(k, days)
    m18_cfg = load_m18_config()
    defects = DefectInjector(
        m18_cfg.defects,
        root=FLEET_ROOT,
        scenario=FLEET_SCENARIO,
        contract=c,
        dict_version=b.dict_version,
        dict_hash=b.dict_hash,
    )
    obs_events: list[tuple[str, dict[str, Any]]] = []

    class Session(OpsSession):
        """OpsSession that also keeps M14's ``obs.event`` downloads (the ``events.*`` rows M14 sends to M18
        at their ingest time): the session's record sink sees only M18/M21 records."""

        def _collect(self, trace):
            for _, ev in trace.dispatched:
                if ev.kind == "obs.event":
                    doc = read_payload(ev.payload)
                    obs_events.append((doc["topic"], doc["row"]))
            super()._collect(trace)

    s = Session(b, FLEET_ROOT, defects=defects)
    policy = ScheduledPolicy()
    n_orders = 0
    for t in b.calendar.epochs(1 * NS, days * DAY):
        s.run_until(t)
        ctx = PolicyContext(
            t_utc=s.t_utc,
            catalogue=m18_cfg.catalogue,
            cann_min_awp_s=m18_cfg.cann_min_awp_s,
            tz_offset_s=m18_cfg.tz_offset_s,
        )
        orders = policy.decide(s.obs, ctx)
        if orders:
            s.submit(orders)
            n_orders += len(orders)
    s.run_until(days * DAY)
    store = _stores(out, "fleet")
    counts: dict[str, int] = {}
    big = 2**62
    for topic in ("maint.records", "orders.commands", "orders.status"):
        tab = s.obs.as_of(big, topic)
        if tab.num_rows:
            store.write(topic, tab.cast(c.schemas[topic]))
        counts[topic] = tab.num_rows
    by_topic: dict[str, list[dict[str, Any]]] = {}
