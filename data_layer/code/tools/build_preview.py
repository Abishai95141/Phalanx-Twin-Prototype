def _sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def validate_tree(tree_root: Path, *, restricted: bool) -> dict[str, Any]:
    """Validate every Parquet file of a tree against the contract with the real validator.

    Consumer files: the exact consumer schema, then ``Contract.validate`` on the file with the restricted
    fields added as nulls (they are nullable by the loader rule). Restricted files: ``labels.truth`` with
    ``Contract.validate``; restricted parts with their exact restricted-part schema."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    c = _contract()
    out: dict[str, Any] = {}
    for f in sorted(tree_root.rglob("*.parquet")):
        topic = f.relative_to(tree_root).parts[0]
        t = pq.read_table(f)
        spec = c.topics[topic]
        if not restricted:
            want = c.consumer_schema(topic)
            if not t.schema.equals(want, check_metadata=False):
                raise ValueError(f"{f}: schema is not the consumer schema of {topic}")
            full = c.schemas[topic]
            cols = [
                t.column(n) if n in t.schema.names else pa.nulls(t.num_rows, full.field(n).type)
                for n in full.names
            ]
            c.validate(topic, pa.Table.from_arrays(cols, schema=full))
        elif spec.restricted:
            c.validate(topic, t.cast(c.schemas[topic]))
        else:
            if not t.schema.equals(c.restricted_part_schema(topic), check_metadata=False):
                raise ValueError(f"{f}: schema is not the restricted part of {topic}")
        e = out.setdefault(topic, {"files": 0, "rows": 0})
        e["files"] += 1
        e["rows"] += t.num_rows
    return out


def finalize(out: Path, manifest_path: Path) -> dict[str, Any]:
    """Validate every file, run the leak audit on each consumer tree, and write MANIFEST.json (sha256 of every
    file, row counts per tree and topic, run outcomes)."""
    from phalanx.streaming.leak_audit import audit_consumer_tree

    c = _contract()
    runs = {
        kind: [json.loads(p.read_text()) for p in sorted((out / "_runs" / kind).glob("*.json"))]
        for kind in ("telemetry", "full_path", "fleet", "determinism")
        if (out / "_runs" / kind).exists()
    }
    secrets: list[Any] = [hex(TELEMETRY_ROOT)[2:].rjust(32, "0"), hex(FLEET_ROOT)[2:].rjust(32, "0")]
    secrets += sorted({r["root_seed_hex"] for r in runs.get("telemetry", []) if r.get("root_seed_hex")})
    trees: dict[str, Any] = {}
    audits: dict[str, list[str]] = {}
    for tree in ("telemetry", "telemetry_full_path", "fleet"):
        if (out / tree).exists():
            trees[tree] = validate_tree(out / tree, restricted=False)
            audits[tree] = audit_consumer_tree(out / tree, c, secrets=secrets)
        if (out / "_restricted_labels" / tree).exists():
            trees[f"_restricted_labels/{tree}"] = validate_tree(
                out / "_restricted_labels" / tree, restricted=True
            )
    for tree in ("telemetry", "telemetry_full_path", "fleet", "ch10"):
        if (out / tree).exists() and any(p.parts[-1] == "labels.truth" for p in (out / tree).iterdir()):
            raise ValueError(f"labels.truth found in consumer tree {tree}")
    files = {
        str(p.relative_to(out)): {"sha256": _sha256(p), "bytes": p.stat().st_size}
        for p in sorted(out.rglob("*"))
        if p.is_file() and p.parts[len(out.parts)] not in ("_work",) and p.name != "MANIFEST.json"
    }
    doc = {
        "preview": PREVIEW_LABEL,
        "preview_version": PREVIEW_VERSION,
        "contract_version": c.version,
        "contract_hash": c.hash,
        "schema_hash": c.schema_hash,
        "generated_by": "tools/build_preview.py",
        "code_commit": git_commit(),
        "seeds": {
            "telemetry": {
                "scenario": TELEMETRY_SCENARIO,
                "root": hex(TELEMETRY_ROOT),
                "plan_days": PLAN_DAYS,
            },
            "fleet": {"scenario": FLEET_SCENARIO, "root": hex(FLEET_ROOT), "start": FLEET_START.isoformat()},
        },
        "sample": {
            "telemetry_sorties": list(TELEMETRY_SORTIES),
            "full_path": {"sortie": FULL_PATH_SORTIE, "window_s": FULL_PATH_WINDOW_S},
            "fleet": {"tails": FLEET_TAILS, "days": FLEET_DAYS},
        },
        "validation": {"trees": trees, "leak_audit_findings": audits},
        "runs": runs,
        "files": files,
    }
    _write_json(out / "MANIFEST.json", doc)
    if manifest_path is not None:
        _write_json(manifest_path, doc)
    return doc


