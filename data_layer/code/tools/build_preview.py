def _sub(args: Sequence[str]) -> int:
    return subprocess.run(
        [sys.executable, "-I", str(Path(__file__).resolve()), *args], check=False
    ).returncode


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sp = ap.add_subparsers(dest="cmd", required=True)
    for name in ("telemetry", "fullpath", "fleet", "finalize", "verify", "all"):
        p = sp.add_parser(name)
        p.add_argument("--out", type=Path, default=DEFAULT_OUT)
        if name in ("telemetry", "verify"):
            p.add_argument("--sortie", required=True, choices=TELEMETRY_SORTIES)
        if name == "telemetry":
            p.add_argument("--max-s", type=int, default=None, help="smoke runs only")
        if name == "fullpath":
            p.add_argument("--window-s", type=int, default=FULL_PATH_WINDOW_S)
        if name == "fleet":
            p.add_argument("--tail-index", type=int, required=True)
            p.add_argument("--days", type=int, default=FLEET_DAYS)
        if name == "finalize":
            p.add_argument("--manifest", type=Path, default=ROOT / "docs" / "previews" / "v0.9_MANIFEST.json")
        if name == "all":
            p.add_argument("--jobs", type=int, default=3)
    a = ap.parse_args(argv)
    out = a.out.resolve()
    if a.cmd == "telemetry":
        print(json.dumps(run_telemetry(a.sortie, out, max_s=a.max_s), indent=1, default=str))
    elif a.cmd == "fullpath":
        print(json.dumps(run_full_path_window(out, window_s=a.window_s), indent=1, default=str))
    elif a.cmd == "fleet":
        print(json.dumps(run_fleet(a.tail_index, out, days=a.days), indent=1, default=str))
    elif a.cmd == "finalize":
        doc = finalize(out, a.manifest)
        print(json.dumps(doc["validation"], indent=1))
    elif a.cmd == "verify":
        print(json.dumps(verify(a.sortie, out), indent=1))
    elif a.cmd == "all":
        jobs = [["telemetry", "--sortie", s, "--out", str(out)] for s in TELEMETRY_SORTIES]
        jobs += [["fullpath", "--out", str(out)]]
        jobs += [["fleet", "--tail-index", str(k), "--out", str(out)] for k in range(FLEET_TAILS)]
        with ProcessPoolExecutor(max_workers=a.jobs) as ex:
            codes = list(ex.map(_sub, jobs))
        if any(codes):
            print(f"failed jobs: {[j for j, c in zip(jobs, codes, strict=True) if c]}")
            return 1
        _sub(["verify", "--sortie", FULL_PATH_SORTIE, "--out", str(out)])
        _sub(["finalize", "--out", str(out)])
    return 0


