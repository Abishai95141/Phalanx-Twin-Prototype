"""Build the published contract documentation into docs/contract/ (W0.X wiring; architecture §16, AD-14).

M01's `build` compiles the Tejas dictionary and runs its manifest generators (TMATS, synthetic ICD, parameter
table, assumptions) plus the W0.4 contract generator, passed through the `extra_generators` hook. Adding that
generator to the manifest itself would change the dictionary hash. The output is deterministic, and
tests/integration/test_w0x_wiring.py checks that docs/contract/ matches a fresh build byte for byte.

Usage: python -I tools/build_contract_docs.py [out_dir]     (default: docs/contract)
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from phalanx.dictionary.generators import build, contract_v0_generator  # noqa: E402

CONFIG = ROOT / "configs" / "tejas" / "dictionary"
README = """# Contract and dictionary documentation (generated)

Generated by `python -I tools/build_contract_docs.py`. **Do not edit by hand.**
`tests/integration/test_w0x_wiring.py` fails if these files drift from a fresh build.

| Path | Content |
|---|---|
| `contract/v0/contract.md` | **Contract v0 summary** (W0.4) |
| `contract/MIGRATION.md` | Contract migration notes, one section per version step (AD-41) |
| `contract/v0/` | Arrow, JSON-Schema and Avro schemas; `dictionary_binding.json` |
| `dictionary.<ver>.json` | Compiled, hashed Tejas dictionary (M01) |
| other files | TMATS stub, synthetic ICD, parameter table, assumption rows |

The bus map (ICD) is the **SYNTHETIC Phalanx ICD**. It is not the real Tejas ICD.
"""


def build_docs(out_dir: Path) -> list[Path]:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    _, written = build(CONFIG, out_dir, extra_generators={"contract": contract_v0_generator})
    (out_dir / "README.md").write_text(README, encoding="utf-8")
    return sorted(p for paths in written.values() for p in paths)


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else ROOT / "docs" / "contract"
    files = build_docs(out)
    print(f"build_contract_docs: wrote {len(files) + 1} files under {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
