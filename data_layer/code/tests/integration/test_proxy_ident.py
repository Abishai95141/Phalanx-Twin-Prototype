"""A2 (W2.4a): the proxy identification machinery (``phalanx.proxy.ident``) on synthetic proxy flights only.

- the deterministic identification model reproduces the full proxy chain without disturbances (the only
  difference is the M13 lane texture the model omits);
- the difference Jacobian is step-size consistent (the AD-22 complex step cannot pass M12's real-only truth
  rows; ident.py docstring);
- transient-weighted output error recovers known parameters from data generated by the full chain with the
  committed disturbance bank and the DASHlink texture (reduced here to two parameters on 40 s; the six-
  parameter self-test is ``analysis/proxy_quicklook/code/a2_selftest.py``, slow test below);
- negative control: fitting from the true values on noise-free data stays at the truth.

Samples: synthetic inputs (cruise, A/T engaged, N1-command steps), 20-120 s (4,800-28,800 truth steps): the
smallest windows that contain accel and decel steps for every identified dynamic.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import numpy as np
import pytest

from phalanx.core.rng import KeyPath
from phalanx.proxy.config import load_proxy_config
from phalanx.proxy.ident import (
    configure,
    fit_oe,
    jacobian,
    nominal,
    prepare,
    record_array,
    simulate,
    transient_weights_of,
)
from phalanx.proxy.inputs import synthetic_inputs
from phalanx.proxy.run import simulate_flight

pytestmark = pytest.mark.integration
AT = {"at_kp": 0.3, "at_ki": 0.2, "at_rate": 0.1}
ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture(scope="module")
def cfg():
    return load_proxy_config()


@pytest.fixture(scope="module")
def short(cfg):
    fp = cfg.fadec_params.replace(**AT)
    inp = synthetic_inputs(20.0, steps=((5.0, 3.0), (12.0, -3.0)))
    return fp, inp, prepare(cfg, inp.replay_inputs(), fadec_params=fp)


def test_ident_model_reproduces_the_chain_without_disturbances(cfg, short):
    fp, inp, prob = short
    y = simulate(prob)
    sf = simulate_flight(
        cfg.with_factors(()), inp, identity=KeyPath.of(scenario="ident-test", tail="T0", sortie=1), root=1,
        fadec_params=fp,
    )  # fmt: skip
    ys = record_array(sf.sensor)
    n = min(len(y), len(ys))
    tol = (0.06, 0.05, 1.0, 6.0)  # N1 %, N2 %, EGT degC, FF lb/h: the lane texture's effect on the loop
    for c, t in enumerate(tol):
        assert np.max(np.abs(y[:n, :, c] - ys[:n, :, c])) < t, c
        assert np.ptp(ys[:n, 0, c]) > 5 * t  # the window has real dynamics to compare


def test_difference_jacobian_is_step_consistent(short):
    """A-W2.4a-20: the central-difference Jacobian at steps 1e-4 and 1e-5 agrees to 1e-4 relative per column.
    The difference has a floor of about 1e-5 to 3e-5 that does not shrink with the step (the engine kernel's
    inner iterations and the A/T rate limit; measured 2026-10-15 with the stage-5 inertias, 1.5e-5 on i_hp),
    far below the O(1) disagreement a limiter or schedule switch inside the window produces (W2.4a-2 stage 5
    manual windows: 0.5-4.1)."""
    _fp, _inp, prob = short
    names = ("i_lp", "i_hp", "gov_kp", "tau_egt", "tau_ff")
    th = nominal(prob, names)
    y = simulate(prob, names, th * 1.05)
    J4 = jacobian(prob, names, th, y)
    J5 = jacobian(prob, names, th, y, h=1e-5)
    for j in range(len(names)):
        a, b = J4[:, j], J5[:, j]
        assert np.max(np.abs(a)) > 0
        assert np.max(np.abs(a - b)) / np.max(np.abs(a)) < 1e-4, names[j]


@pytest.mark.parametrize(("bank_scale", "tol"), [(0.0, 0.05), (1.0, None)])
def test_oe_recovers_known_parameters_from_the_textured_chain(cfg, bank_scale, tol):
    """A2 (reduced): LP inertia x1.4 and EGT thermocouple tau 0.81 -> 1.10 s, identified from the full chain's
    recorded words (DASHlink texture always on). With the disturbance bank off (scale 0) both are recovered
    within 5 %. With the committed placeholder bank (scale 1) a 40 s window does not identify them to 10 %
    (A2 finding: run 1 of the six-parameter self-test, analysis/proxy_quicklook/README.md): the fit must still
    lower the cost and move both estimates towards the truth. Negative control: a fit started at the truth
    on the model's own output stays there."""
    from dataclasses import replace

    fp = cfg.fadec_params.replace(**AT)
    inp = synthetic_inputs(40.0, steps=((8.0, 3.0), (20.0, -3.0), (30.0, 2.0)))
    rec = inp.replay_inputs()
    prob = prepare(cfg, rec, fadec_params=fp)
    names = ("i_lp", "tau_egt")
    th0 = nominal(prob, names)
    truth = {"i_lp": th0[0] * 1.4, "tau_egt": 1.10}
    tv = np.array([truth[k] for k in names])
    cfg_t, fp_t = configure(cfg, truth, fp)
    bank = tuple(
        f if f.group != 0 else replace(f, loadings=tuple(x * bank_scale for x in f.loadings))
        for f in cfg_t.env.factors
    )
    sf = simulate_flight(
        cfg_t.with_factors(bank),
        inp,
        identity=KeyPath.of(scenario="a2-test", tail="T687", sortie=1),
        root=2026,
        fadec_params=fp_t,
    )
    y = record_array(sf.record)
    w = transient_weights_of(rec)[: y.shape[0]]
    fit = fit_oe(prob, y, names, th0, weights=w)
    ratio = fit.theta / tv
    assert fit.cost < (0.7 if bank_scale == 0.0 else 1.0) * fit.cost0  # disturbances dominate at scale 1
    if tol is not None:
        assert np.all(np.abs(ratio - 1.0) < tol), (ratio, fit)
    else:
        assert np.all(np.abs(np.log(ratio)) < np.abs(np.log(th0 / tv))), (ratio, fit)
    if bank_scale == 0.0:
        clean = simulate(prob, names, tv)
        again = fit_oe(prob, clean, names, tv, weights=w, max_iter=3)
        assert np.allclose(again.theta, tv, rtol=1e-6)


class JointFitIllConditioned(AssertionError):
    """The joint six-parameter A2 fit on one A/T-step flight misses the truth by > 5 % at texture only."""


@pytest.mark.slow
@pytest.mark.xfail(
    strict=True,
    raises=JointFitIllConditioned,
    reason=(
        "W2.4a-1 A2 finding (analysis/proxy_quicklook/README.md, A2): the joint six-parameter fit on one "
        "A/T-step flight is ill-conditioned - the A/T outer loop hides the inner governor, the governor "
        "gains are the weakest directions (Jacobian condition 22) and absorb the model's missing lane "
        "texture. Texture-only rung (scale0.0_ar0) estimate/truth for (i_lp, i_hp, gov_kp, gov_ki): "
        "W2.4a-1 0.96, 0.86, 0.77, 0.69 (cost 12,167 -> 2,746); main 971a37a+ 0.9688, 0.8982, 0.8073, "
        "0.1048 (cost0 3231.343 -> cost 3231.343); W2.4a-2 plant (stage-1 identified, A/T floor) 1.006, "
        "1.008, 1.046, 1.273, the sensor lags 1.00 - only gov_ki misses. The adopted route is the staged "
        "indirect identification (AD-52 item 5: plant and sensor lags on A/T segments, governor gains on "
        "manual lever segments), which a2_subset.json passes"
    ),
)
def test_a2_six_parameter_ladder(tmp_path):
    """The six-parameter A2 self-test as a signal-to-disturbance ladder (analysis/proxy_quicklook/code/
    a2_ladder.py): texture only -> within 5 %; a quarter of the committed bank -> within 10 %. Strict xfail
    on the texture-only rung only (``JointFitIllConditioned``); any other failure is a plain failure, and a
    joint fit that starts to pass turns the strict xfail into a failure to be looked at."""
    import json
    import sys

    code = ROOT / "analysis" / "proxy_quicklook" / "code"
    sys.path.insert(0, str(code))
    spec = importlib.util.spec_from_file_location("a2_ladder", code / "a2_ladder.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    out = tmp_path / "a2_ladder.json"
    mod.main(str(out))
    res = json.loads(out.read_text())
    if not res["pass"]["scale0_within_5pct"]:
        raise JointFitIllConditioned(res["runs"]["scale0.0_ar0"])
    assert res["pass"]["scale0.25_within_10pct"], res["runs"]
